import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { codegen } from '@graphql-codegen/core';
import { parse, buildASTSchema, validate } from 'graphql';
import * as typescript from '@graphql-codegen/typescript';
import * as typescriptOperations from '@graphql-codegen/typescript-operations';

const schema = parse(await readFile(new URL('../ms/orbita-api/graphql/client.graphql',import.meta.url),'utf8'));
const documents = [];
async function visit(path) {
  for (const entry of await readdir(path,{withFileTypes:true})) {
    const file = join(path,entry.name);
    if (entry.isDirectory()) await visit(file);
    else if (entry.name.endsWith('.graphql')) documents.push({location:file,document:parse(await readFile(file,'utf8'))});
  }
}
await visit(new URL('../ms/orbita-front/src',import.meta.url).pathname);
await visit(new URL('../ms/orbita-admin/src',import.meta.url).pathname);
const graph = buildASTSchema(schema);
for(const document of documents) {
  const errors=validate(graph,document.document);
  if(errors.length) throw new Error(`${document.location}: ${errors.map(e=>e.message).join('; ')}`);
}
const output = await codegen({filename:'generated.ts',schema,documents,plugins:[{typescript:{}},{typescriptOperations:{}}],pluginMap:{typescript,'typescriptOperations':typescriptOperations},config:{scalars:{Decimal:'string',DateTime:'string',JSON:'unknown'},useTypeImports:true}});
for (const service of ['front','admin']) await writeFile(new URL(`../ms/orbita-${service}/packages/contracts/src/generated.ts`,import.meta.url),'// Generated by npm --prefix scripts run generate:types; do not edit.\n'+output);
console.log(`Generated schema and ${documents.length} GraphQL operation documents.`);
